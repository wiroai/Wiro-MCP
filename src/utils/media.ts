// Media produced by workflows and agents, presented the same way run_model
// presents task outputs: a text block, an assistant-only reminder to show the
// media, and one resource link per file. Only files on Wiro's own hosts are
// presented this way. Agent replies can carry addresses taken from mail or web
// pages the agent read, so any other address stays a plain link in the text.

export interface MediaItem {
  url: string;
  name?: string;
  mimeType?: string;
}

export type MediaContentBlock =
  | {
    type: 'text';
    text: string;
    annotations?: { audience: Array<'user' | 'assistant'>; priority: number };
  }
  | {
    type: 'resource_link';
    uri: string;
    name: string;
    description: string;
    mimeType?: string;
    annotations?: { audience: Array<'user' | 'assistant'>; priority: number };
  };

const EXTENSION_MIME_TYPES: Record<string, string> = {
  png: 'image/png',
  jpg: 'image/jpeg',
  jpeg: 'image/jpeg',
  webp: 'image/webp',
  gif: 'image/gif',
  mp4: 'video/mp4',
  webm: 'video/webm',
  mov: 'video/quicktime',
  mp3: 'audio/mpeg',
  wav: 'audio/wav',
  m4a: 'audio/mp4',
  pdf: 'application/pdf',
};

export function guessMimeType(url: string): string | undefined {
  const path = url.split(/[?#]/)[0] ?? '';
  const extension = path.split('.').pop()?.toLowerCase() ?? '';
  return EXTENSION_MIME_TYPES[extension];
}

/** An http(s) address on wiro.ai or one of its subdomains. */
export function isWiroHostedUrl(url: string): boolean {
  let parsed: URL;
  try {
    parsed = new URL(url);
  } catch {
    return false;
  }
  if (parsed.protocol !== 'https:' && parsed.protocol !== 'http:') return false;
  const host = parsed.hostname.toLowerCase();
  return host === 'wiro.ai' || host.endsWith('.wiro.ai');
}

export function createMediaContent(text: string, items: MediaItem[]): MediaContentBlock[] {
  const content: MediaContentBlock[] = [{ type: 'text', text }];
  const unique = items.filter((item, index) =>
    isWiroHostedUrl(item.url) && items.findIndex(candidate => candidate.url === item.url) === index);
  if (unique.length === 0) return content;

  content.push({
    type: 'text',
    text: 'Present every generated media output in your user-facing response now. '
      + 'For images, render the resource URL inline with Markdown image syntax and '
      + 'keep it clickable. For video, audio, and other files, provide a clickable '
      + 'link. Do not return only metadata or merely say that media was generated.',
    annotations: { audience: ['assistant'], priority: 1 },
  });

  for (const item of unique) {
    const mimeType = item.mimeType || guessMimeType(item.url);
    content.push({
      type: 'resource_link',
      uri: item.url,
      name: item.name || 'Wiro output',
      description: 'Generated by Wiro. Present this media in the user-facing response.',
      ...(mimeType ? { mimeType } : {}),
      annotations: { audience: ['user', 'assistant'], priority: 1 },
    });
  }
  return content;
}
